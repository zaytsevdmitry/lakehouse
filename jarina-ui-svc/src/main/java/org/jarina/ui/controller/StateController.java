package org.jarina.ui.controller;

import org.jarina.client.api.dto.state.DataSetStateDTO;
import org.jarina.ui.dto.DataSetStateRequestDTO;
import org.jarina.ui.service.StateService;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import java.util.List;

@RestController
@RequestMapping("/api/states")
public class StateController {

    private final StateService stateService;

    public StateController(StateService stateService) {
        this.stateService = stateService;
    }

    @PostMapping
    public List<DataSetStateDTO> getStates(@RequestBody DataSetStateRequestDTO request) {
        return stateService.getStates(request);
    }
}
